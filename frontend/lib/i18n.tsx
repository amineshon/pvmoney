const intlLocale: Record<Locale, string> = { fa: "fa-IR", en: "en-US", de: "de-DE" };

type Ctx = {
  locale: Locale;
  dir: "rtl" | "ltr";
  setLocale: (l: Locale) => void;
  t: (key: string, vars?: Record<string, string | number>) => string;
  label: (raw: string) => string;
  intl: string;
};

const I18nContext = createContext<Ctx | null>(null);

function fill(s: string, vars?: Record<string, string | number>) {
  if (!vars) return s;
  return s.replace(/\{(\w+)\}/g, (_, k) => String(vars[k] ?? ""));
}

export function LocaleProvider({ children }: { children: ReactNode }) {
  const [locale, setLocaleState] = useState<Locale>("fa");

  useEffect(() => {
    const saved = localStorage.getItem(KEY) as Locale | null;
    if (saved === "fa" || saved === "en" || saved === "de") setLocaleState(saved);
  }, []);

  useEffect(() => {
    const meta = LOCALES.find((l) => l.id === locale)!;
    document.documentElement.lang = locale;
    document.documentElement.dir = meta.dir;
    document.documentElement.classList.toggle("ltr", meta.dir === "ltr");
    localStorage.setItem(KEY, locale);
  }, [locale]);

  const value = useMemo<Ctx>(() => {
    const dict = DICTS[locale];
    const t = (key: string, vars?: Record<string, string | number>) => fill(dict[key] || key, vars);
    const label = (raw: string) => {
      if (!raw) return raw;
      const aliased = CAT_ALIAS[raw] || raw;
      const typed = dict[`type.${aliased}`];
      if (typed) return typed;
      const cat = dict[`cat.${aliased}`];
      if (cat) return cat;
      const unit = dict[`unit.${aliased}`];
      if (unit) return unit;
      return raw;
    };
    return {
      locale,
      dir: LOCALES.find((l) => l.id === locale)!.dir,
      setLocale: setLocaleState,
      t,
      label,
      intl: intlLocale[locale],
    };
  }, [locale]);

  return <I18nContext.Provider value={value}>{children}</I18nContext.Provider>;
}

export function useI18n() {
  const ctx = useContext(I18nContext);
  if (!ctx) throw new Error("useI18n outside provider");
  return ctx;
}

